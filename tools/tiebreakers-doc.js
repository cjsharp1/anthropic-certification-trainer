/* Writes docs/TIEBREAKERS.md from data-tiebreakers.js.
 *
 * The app renders the same entries on the Exam Simulation start screen. The
 * markdown is generated rather than hand-written so the two cannot drift:
 * edit the data file, then run `npm run docs:tiebreakers`.
 *
 *   node tools/tiebreakers-doc.js           write the file
 *   node tools/tiebreakers-doc.js --check   exit 1 if the file is stale
 *
 * Unlike the app, the doc lists the bank ids that turn on each principle.
 * It is for people working in the repo, where seeing an answer spoils
 * nothing, and the ids are the quickest way to go and read the real ones.
 */
const fs = require('fs');
const vm = require('vm');
const PATHS = require('./paths');

const OUT = PATHS.resolve('docs/TIEBREAKERS.md');

function load() {
  const ctx = {};
  vm.createContext(ctx);
  vm.runInContext([
    fs.readFileSync(PATHS.resolve('data-sim-questions.js'), 'utf8'),
    fs.readFileSync(PATHS.resolve('data-tiebreakers.js'), 'utf8'),
    ';globalThis.__d={SIM_QUESTIONS,TIEBREAKERS,TIEBREAKER_REFLEXES};'
  ].join('\n;\n'), ctx);
  return ctx.__d;
}

function render({ SIM_QUESTIONS, TIEBREAKERS, TIEBREAKER_REFLEXES }) {
  const idsFor = t => SIM_QUESTIONS.filter(q => t.tags.includes(q.tiebreaker)).map(q => q.id);
  const list = TIEBREAKERS.map(t => ({ t, ids: idsFor(t) }))
    .sort((a, b) => b.ids.length - a.ids.length);
  const code = s => '`' + s + '`';
  const L = [];

  L.push('# Tiebreakers');
  L.push('');
  L.push('<!-- Generated by tools/tiebreakers-doc.js from src/data/data-tiebreakers.js.');
  L.push('     Edit the data file and run `npm run docs:tiebreakers`; do not edit this file. -->');
  L.push('');
  L.push('On the CCAR-F exam, two of the four options often both work. The question is');
  L.push('which one is *best*, and a small set of principles decides that again and again.');
  L.push('Every Exam Simulation question names the principle that separates its best answer');
  L.push('from the runner-up. This page collects the ones that recur.');
  L.push('');
  L.push('The examples are written for this guide rather than taken from the bank, so');
  L.push('reading them does not spoil any sim question. The same content appears in the app');
  L.push('on the Exam Simulation start screen.');
  L.push('');
  L.push('## At a glance');
  L.push('');
  L.push('| Principle | Rule | Questions |');
  L.push('|---|---|--:|');
  list.forEach(({ t, ids }) =>
    L.push('| [' + t.name + '](#' + t.id + ') | ' + t.rule + ' | ' + ids.length + ' |'));
  L.push('');
  L.push('## Working a two-good-options question');
  L.push('');
  L.push('1. List every requirement in the stem, including the quiet ones: *must*, *every*,');
  L.push('   *lowest cost*, *without the subagent asking again*.');
  L.push('2. Strike anything the stem has already ruled out, such as a fix it says is in place.');
  L.push('3. Of what is left, ask which option is guaranteed rather than likely, and which fixes');
  L.push('   the cause rather than the symptom.');
  L.push('4. If two options still both work, prefer the smaller change and the built-in feature.');
  L.push('');

  // Reflexes first: they are the quickest thing here to use, and at the
  // end of fourteen principles they were the part readers never reached.
  L.push('## Quick reflexes');
  L.push('');
  L.push('The fix the exam expects first for a familiar symptom. If the stem says that fix');
  L.push('is already in place, it is testing [what the scenario rules out](#ruled-out) instead.');
  L.push('');
  L.push('| Symptom | First fix | Bank questions |');
  L.push('|---|---|---|');
  TIEBREAKER_REFLEXES.firstStep.forEach(r =>
    L.push('| ' + r.symptom + ' | ' + r.fix + ' | ' + r.q.map(code).join(', ') + ' |'));
  L.push('');
  L.push('Options that are almost never the answer:');
  L.push('');
  TIEBREAKER_REFLEXES.wrong.forEach(w =>
    L.push('- **' + w.level + ' wrong:** ' + w.text + ' (' + w.q.map(code).join(', ') + ')'));
  L.push('');
  list.forEach(({ t, ids }) => {
    L.push('<a id="' + t.id + '"></a>');
    L.push('');
    L.push('## ' + t.name);
    L.push('');
    L.push('**' + t.rule + '**');
    L.push('');
    L.push('- **How to spot it:** ' + t.spot);
    L.push('- **The runner-up:** ' + t.trap);
    L.push('');
    L.push('> **Example.** ' + t.example.situation);
    L.push('>');
    L.push('> - ✅ **Best:** ' + t.example.best);
    L.push('> - ➖ **Runner-up:** ' + t.example.runnerUp);
    L.push('>');
    L.push('> ' + t.example.why);
    L.push('');
    L.push('Bank questions (' + ids.length + '): ' + ids.map(code).join(', '));
    L.push('');
  });

  return L.join('\n');
}

if (require.main === module) {
  const md = render(load());
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur.replace(/\r\n/g, '\n') !== md) {
      console.log('docs/TIEBREAKERS.md is stale: run npm run docs:tiebreakers');
      process.exit(1);
    }
    console.log('docs/TIEBREAKERS.md is current');
  } else {
    fs.writeFileSync(OUT, md);
    console.log('wrote docs/TIEBREAKERS.md');
  }
}

module.exports = { load, render, OUT };
